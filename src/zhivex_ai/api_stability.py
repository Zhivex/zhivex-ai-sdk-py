def build_api_stability_manifest(
    export_modules: Mapping[str, str] | None = None,
) -> dict[str, ApiStabilityEntry]:
    resolved_export_modules: Mapping[str, str]
    if export_modules is None:
        from . import _EXPORTS

        resolved_export_modules = _EXPORTS
    else:
        resolved_export_modules = export_modules

    return {
        name: ApiStabilityEntry(
            name=name,
            level=level,
            category=_CATEGORY_BY_MODULE[resolved_export_modules[name]],
            notes=_NOTES_BY_EXPORT.get(name, ""),
        )
        for name, level in sorted(_EXPORT_LEVELS.items())
    }


API_STABILITY = build_api_stability_manifest()


def get_api_stability(name: str) -> ApiStabilityEntry:
    return API_STABILITY[name]
